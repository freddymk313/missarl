import { requireSession } from "@/lib/auth";
import { getClients } from "@/lib/db/clients";
import { getItems, getItemCategories, getBrands, getUnits } from "@/lib/db/items";
import { getSuppliers } from "@/lib/db/suppliers";
import { QuotationWizard } from "@/components/dashboard/quotation-wizard";
import { PageHeader } from "@/components/dashboard/ui/page-header";

export default async function NewQuotationPage({
  searchParams,
}: {
  searchParams: Promise<{ clientId?: string }>;
}) {
  await requireSession(["SUPER_ADMIN", "ADMIN"]);
  const { clientId } = await searchParams;

  const [clients, items, categories, brands, units, suppliers] =
    await Promise.all([
      getClients(),
      getItems({ activeOnly: true }),
      getItemCategories(),
      getBrands(),
      getUnits(),
      getSuppliers(),
    ]);

  return (
    <div className="space-y-6 max-w-7xl mx-auto">
      <PageHeader
        title="New Quotation / Proforma Invoice"
        description="A unique internal reference will be transactionally generated by the system for the selected client."
      />

      <QuotationWizard
        clients={clients}
        items={items}
        categories={categories}
        brands={brands}
        units={units}
        suppliers={suppliers}
        preselectedClientId={clientId}
      />
    </div>
  );
}